# --------------------------------------------------------------------------- statistics helpers
def cp_ci(k, n, a=0.05):
    lo = stats.beta.ppf(a/2, k, n-k+1) if k > 0 else 0.0
    hi = stats.beta.ppf(1-a/2, k+1, n-k) if k < n else 1.0
    return lo, hi

def n_to_exclude(p_true, p0=0.12, power=0.8, a=0.05):
    """Smallest single-arm N whose exact 95% CI lower bound exceeds p0 with the given power."""
    for n in range(8, 800):
        kmin = next((k for k in range(n+1) if cp_ci(k, n, a)[0] > p0), None)
        if kmin is not None and 1 - stats.binom.cdf(kmin-1, n, p_true) >= power:
            return n, kmin
    return None, None

