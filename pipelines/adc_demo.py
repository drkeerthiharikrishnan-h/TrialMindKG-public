def make_synthetic_internal(seed=2026):
    rng = np.random.default_rng(seed)
    dl = sum([[k]*v for k, v in GENERATOR_ASSUMPTIONS["dose_levels"].items()], [])
    n = len(dl); di = np.array([int(x[-1]) - 1 for x in dl])
    adsl = pd.DataFrame(dict(
        USUBJID=[f"SYN-001-{i:03d}" for i in range(1, n+1)], STUDYID="SYN-TUB040-PH1B", DOSELVL=dl,
        AGE=rng.normal(62, 9, n).round().astype(int),
        PRIORLN=np.clip(1 + rng.poisson(1.6, n), 1, 6),
        PRIPARPI=rng.random(n) < 0.62, PRIBEV=rng.random(n) < 0.78,
        PRIFRADC=rng.random(n) < 0.22,                     # prior mirvetuximab (FRalpha ADC)
        BRCAMUT=rng.random(n) < 0.18, DATACLASS=SYN))
    high = rng.random(n) > 0.15
    tps = np.where(high, rng.beta(5, 1.6, n), rng.beta(0.8, 6, n)) * 100
    adbm = pd.DataFrame(dict(USUBJID=adsl.USUBJID, PARAM="NaPi2b IHC tumour proportion score (%)",
                             TPS=tps.round(0), HSCORE=np.clip(tps * rng.uniform(1.2, 2.8, n), 0, 300).round(0),
                             READER="central pathology (synthetic)", DATACLASS=SYN))
    cavg = 10 * np.array([1.0, 1.3, 1.6, 2.0])[di] * rng.lognormal(0, 0.3, n)
    lp = (-2.4 + 0.75*di + 0.9*(tps >= 10) - 0.6*adsl.PRIFRADC - 0.15*np.maximum(adsl.PRIORLN - 2, 0))
    resp = rng.random(n) < 1/(1+np.exp(-lp))
    bor = np.where(resp, np.where(rng.random(n) < 0.08, "CR", "PR"), np.where(rng.random(n) < 0.55, "SD", "PD"))
    adrs = pd.DataFrame(dict(USUBJID=adsl.USUBJID, PARAMCD="BOR", AVALC=bor, CONFIRMED=resp, DATACLASS=SYN))
    adpc = pd.DataFrame(dict(USUBJID=adsl.USUBJID, PARAM="ADC Cavg cycle 1 (ug/mL)", CAVG=cavg.round(1), DATACLASS=SYN))
    pfs = np.where(resp, rng.exponential(10/np.log(2), n), rng.exponential(3.5/np.log(2), n))
    cens = rng.exponential(14, n)
    adtte = pd.DataFrame(dict(USUBJID=adsl.USUBJID, PARAMCD="PFS", AVAL=np.minimum(pfs, cens).round(2),
                              CNSR=(cens < pfs).astype(int), DATACLASS=SYN))
    ae = []
    for i, u in enumerate(adsl.USUBJID):
        if rng.random() < 1/(1+np.exp(-(-4.6 + 0.10*cavg[i]))):
            ae.append((u, "Interstitial lung disease" if rng.random() < .5 else "Pneumonitis", int(rng.choice([1, 2, 2, 3]))))
